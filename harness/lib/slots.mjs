// Slot bookkeeping for parallel worktrees. Pure functions only: no file system, no git, no
// database. Slot 0 is the main checkout; worktrees take slots 1..MAX_SLOTS.
// Scheme: docs/repository-structure.md ("Ports and worktree isolation"). The base ports are the
// main checkout's configuration, not code: callers read them from the environment (.env.example
// documents them) and validate them with basePortsFrom. Each worktree also owns one database,
// named by databaseName.

import { createHash } from "node:crypto";

export const MAX_SLOTS = 9;
export const PORT_STEP = 10;
export const PORT_VARIABLES = Object.freeze([
  "WEB_PORT",
  "API_PORT",
  "MCP_ADMIN_PORT",
  "LLM_AGENT_PORT",
]);

const HIGHEST_PORT = 2 ** 16 - 1;

// Validates the base port of every service from string settings such as process.env. Each must be
// a whole number that still is a valid port in the highest slot.
export function basePortsFrom(values) {
  const highest = HIGHEST_PORT - MAX_SLOTS * PORT_STEP;
  const ports = {};
  for (const name of PORT_VARIABLES) {
    const value = values?.[name];
    if (value === undefined) {
      throw new Error(`${name} is not set; set it in the environment (documented in .env.example)`);
    }
    const port = /^[0-9]+$/.test(value) ? Number(value) : NaN;
    if (!(port >= 1 && port <= highest)) {
      throw new Error(`${name} must be a whole number from 1 to ${highest}, got "${value}"`);
    }
    ports[name] = port;
  }
  return Object.freeze(ports);
}

export function emptyState() {
  return { slots: {} };
}

export function portsForSlot(slot, basePorts) {
  if (!Number.isInteger(slot) || slot < 0 || slot > MAX_SLOTS) {
    throw new RangeError(`slot must be an integer between 0 and ${MAX_SLOTS}, got ${slot}`);
  }
  return Object.fromEntries(
    PORT_VARIABLES.map((name) => [name, basePorts[name] + slot * PORT_STEP]),
  );
}

export function slotOf(state, owner) {
  for (const [slot, holder] of Object.entries(state.slots)) {
    if (holder === owner) return Number(slot);
  }
  return null;
}

// Gives `owner` the lowest free slot. Idempotent: an owner that already holds a slot keeps it.
export function allocateSlot(state, owner) {
  if (!owner) throw new TypeError("owner is required");
  const existing = slotOf(state, owner);
  if (existing !== null) return { slot: existing, state };
  for (let slot = 1; slot <= MAX_SLOTS; slot += 1) {
    if (!(String(slot) in state.slots)) {
      return { slot, state: { ...state, slots: { ...state.slots, [slot]: owner } } };
    }
  }
  throw new Error(`no free worktree slot: all ${MAX_SLOTS} are taken`);
}

export function freeSlot(state, owner) {
  const slots = Object.fromEntries(
    Object.entries(state.slots).filter(([, holder]) => holder !== owner),
  );
  return { ...state, slots };
}

// Folder name for a branch: `feat/12-profile-api` -> `feat-12-profile-api`.
export function worktreeDirName(branch) {
  const name = String(branch)
    .trim()
    .replace(/[^A-Za-z0-9._-]+/g, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "");
  if (!name) throw new Error(`cannot derive a folder name from branch "${branch}"`);
  return name;
}

// Postgres identifiers are at most 63 bytes. A worktree database name is `wt_<slug>_<hash>`: the
// prefix keeps it apart from the main checkout's database, the slug keeps it readable, and the
// hash of the worktree folder name keeps folders that normalise alike (`a.b`, `a-b`, `A-B`) and
// long names that share a beginning apart. It depends only on the folder name, so a branch and
// its folder give the same database.
const IDENTIFIER_LIMIT = 63;
const DATABASE_PREFIX = "wt_";
const HASH_LENGTH = 10;

export function databaseName(branch) {
  let folder;
  try {
    folder = worktreeDirName(branch);
  } catch {
    throw new Error(`cannot derive a database name from branch "${branch}"`);
  }
  const hash = createHash("sha256").update(folder).digest("hex").slice(0, HASH_LENGTH);
  const room = IDENTIFIER_LIMIT - DATABASE_PREFIX.length - hash.length - 1;
  const slug = folder
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .slice(0, room)
    .replace(/^_+|_+$/g, "");
  return `${DATABASE_PREFIX}${slug ? `${slug}_` : ""}${hash}`;
}

export function envFileContent(slot, basePorts, extra = {}) {
  const values = { WORKTREE_SLOT: slot, ...portsForSlot(slot, basePorts), ...extra };
  const lines = Object.entries(values).map(([key, value]) => `${key}=${value}`);
  return `# Generated by harness/worktree.mjs. Local development settings.\n${lines.join("\n")}\n`;
}

// Branch names of docs/git-workflow.md. An issue branch is `<type>/<issue-number>-<slug>` with a
// Conventional Commits type; a phase branch is `phase/<phase-folder>`. An issue number has no
// leading zero, which a phase folder below 10 (`06-llm-agent`) always has.
const ISSUE_BRANCH = /^(?:feat|fix|docs|refactor|test|chore|ci)\/([1-9][0-9]*)-/;
const PHASE_BRANCH = /^(?:origin\/)?phase\/(.+)$/;

// The phase folder of a phase branch, local or as `origin/<name>`; null for any other ref.
export function phaseFolderOf(ref) {
  return String(ref).match(PHASE_BRANCH)?.[1] ?? null;
}

// The issue number in a branch name, or null. A name that starts with a known phase folder
// (`docs/15-pages-prd` in phase `15-pages`) carries that phase's number, not an issue's.
function issueOf(name, phaseFolders) {
  const issue = name.match(ISSUE_BRANCH)?.[1];
  if (!issue) return null;
  const slug = name.slice(name.indexOf("/") + 1);
  if (phaseFolders.some((folder) => slug === folder || slug.startsWith(`${folder}-`))) return null;
  return issue;
}

// Returns an existing branch of the same issue under another name, so an interrupted issue is
// continued rather than started again, or null when the requested branch is to be created.
// `branches` lists local names and remote ones as `origin/<name>`; a local branch wins over a
// remote one. A number in a branch name is an issue number only by convention, so all of these
// must hold (issue 323):
//   - `base`, the ref the requested branch is cut from, is a phase branch: only issue branches are
//     cut from one. Without `base` the caller vouches for that; createWorktree always passes it.
//   - Both names are issue branches (see issueOf) with the same number. A phase branch is neither
//     continued nor continued on; phase folders are known from `base` and from `branches`.
//   - `merged(name)` is false for the other branch: finished work is not continued. It is asked
//     only about branches of the same issue, with the name as listed.
export function existingIssueBranch(branch, branches, { base, merged = () => false } = {}) {
  if (base !== undefined && phaseFolderOf(base) === null) return null;
  const phaseFolders = [base ?? "", ...branches].map(phaseFolderOf).filter(Boolean);
  const issue = issueOf(String(branch), phaseFolders);
  if (!issue) return null;
  const localName = (name) => (name.startsWith("origin/") ? name.slice("origin/".length) : name);
  const candidates = branches.filter(
    (name) => localName(name) !== branch && issueOf(localName(name), phaseFolders) === issue,
  );
  const isRemote = (name) => name.startsWith("origin/");
  const found =
    candidates.find((name) => !isRemote(name) && !merged(name)) ??
    candidates.find((name) => isRemote(name) && !merged(name));
  return found === undefined ? null : localName(found);
}

// The storage folder of a worktree below `<environment>/`, STORAGE_WORKTREE: `<slug>-<hash>`, at most
// 63 characters of lower-case letters, digits and hyphens. Like databaseName it depends only on the
// folder name, and the hash keeps folders that normalise alike apart, so no two worktrees share a
// storage folder.
const STORAGE_FOLDER_LIMIT = 63;

export function storageWorktreeName(branch) {
  let folder;
  try {
    folder = worktreeDirName(branch);
  } catch {
    throw new Error(`cannot derive a storage folder name from branch "${branch}"`);
  }
  const hash = createHash("sha256").update(folder).digest("hex").slice(0, HASH_LENGTH);
  const room = STORAGE_FOLDER_LIMIT - hash.length - 1;
  const slug = folder
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .slice(0, room)
    .replace(/^-+|-+$/g, "");
  return slug ? `${slug}-${hash}` : hash;
}
