/**
 * The chat contract: what a visitor submits and the ordered events of one answer attempt.
 *
 * - A submission names its conversation (random, client-generated, it authorises nothing), a
 *   client-generated request identifier for this one question and the trimmed question.
 * - Every event of an attempt carries the request it answers, the assistant message it builds and
 *   an event identifier that grows by arrival order. Events form a discriminated union on `type`:
 *   `start`, `text_delta`, `block` (one complete typed block), `sources` (at most once),
 *   `related` (at most once, one or two links), `complete` (with its outcome) and `error` (with a
 *   stable code and whether retrying can help).
 * - An attempt begins with `start`, or fails at once with `error`. Exactly one terminal event —
 *   `complete` or `error` — ends it; nothing may follow. A stream that ends earlier is
 *   interrupted. An event whose identifier is not above the last accepted one is a duplicate and
 *   is ignored.
 * - Links are safe: site paths (`/…`, never `//…`), or `http`/`https` addresses where a link may
 *   leave the site. Sources always point to an exact place on the site.
 *
 * The contract is transport-free: the phase 3 browser mock and the phase 7 API adapter both
 * deliver these events, and the same scenarios (`validateChatStream`) hold for both.
 */
import { z } from "zod";

import { explorationStatuses } from "../profile/index.js";

/** The longest question a visitor may submit, in characters after trimming. */
export const chatQuestionMaxLength = 1000;

/**
 * How a completed answer ended: answered from the public profile, not enough evidence to answer,
 * refused (outside what the assistant answers) or the assistant unavailable for this question.
 */
export const chatOutcomes = [
  "answered",
  "insufficient_evidence",
  "refused",
  "unavailable",
] as const;

export type ChatOutcome = (typeof chatOutcomes)[number];

/** The stable codes of a failed attempt; whether a retry may help is a flag of its own. */
export const chatErrorCodes = [
  "invalid_request",
  "rate_limited",
  "unavailable",
  "timeout",
  "invalid_stream",
  "internal",
] as const;

export type ChatErrorCode = (typeof chatErrorCodes)[number];

/** The typed blocks an answer can carry besides text. */
export const chatBlockTypes = [
  "ContactCard",
  "ExperienceCard",
  "ServiceCard",
  "ExplorationCard",
  "RoadmapCard",
] as const;

export type ChatBlockType = (typeof chatBlockTypes)[number];

/** The kinds of profile record a source can rest on. */
export const chatSourceKinds = [
  "person",
  "experience",
  "project",
  "exploration",
  "service",
  "technology_group",
  "roadmap_item",
] as const;

export type ChatSourceKind = (typeof chatSourceKinds)[number];

const text = (max: number) => z.string().trim().min(1).max(max);

/**
 * A path on this site, with an optional query and anchor: it starts with a single `/` and has no
 * whitespace, control characters or backslashes (the services contract's rule), so it can carry
 * neither a scheme nor another host.
 */
const SitePathSchema = z
  .string()
  .max(2048)
  .regex(/^\/(?!\/)[^\s\\\p{Cc}]*$/u, "Must be a path on this site, such as /experience#anchor.")
  .meta({ description: "A path on this site with an optional anchor, such as `/experience#…`." });

const HttpUrlSchema = z.url({ protocol: /^https?$/, hostname: z.regexes.domain }).max(2048);

/** Where a link may lead: a page of this site or an `http`/`https` address. */
const SafeHrefSchema = z.union([SitePathSchema, HttpUrlSchema]);

/** One question of a conversation, as the visitor submits it. */
export const ChatSubmissionSchema = z
  .object({
    conversationId: z.uuid().meta({
      description: "The conversation, random and generated by the client; it authorises nothing.",
    }),
    requestId: z.uuid().meta({
      description: "This question's request, generated by the client; a retry reuses it.",
    }),
    question: text(chatQuestionMaxLength),
  })
  .meta({ id: "ChatSubmission" });

export type ChatSubmission = z.infer<typeof ChatSubmissionSchema>;

/** A place on the site an answer rests on: the record and its exact path with the anchor. */
export const ChatSourceSchema = z
  .object({
    record: z.object({ kind: z.enum(chatSourceKinds), id: text(200) }),
    title: text(200),
    href: SitePathSchema,
  })
  .meta({ id: "ChatSource" });

export type ChatSource = z.infer<typeof ChatSourceSchema>;

/** The payload of the Sources block: the places an answer rests on, at least one, at most eight. */
export const ChatSourcesSchema = z
  .array(ChatSourceSchema)
  .min(1)
  .max(8)
  .meta({ id: "ChatSources" });

/** A link onward from an answer. */
export const ChatRelatedLinkSchema = z
  .object({ label: text(100), href: SafeHrefSchema })
  .meta({ id: "ChatRelatedLink" });

export type ChatRelatedLink = z.infer<typeof ChatRelatedLinkSchema>;

const IsoDateSchema = z.iso.date();

/** A contact link of the contact card; named so every generated client has one model for it. */
const ChatContactLinkSchema = z
  .object({ label: text(100), url: HttpUrlSchema })
  .meta({ id: "ChatContactLink" });

const ContactCardSchema = z.object({
  type: z.literal("ContactCard"),
  email: z.email().nullable(),
  links: z.array(ChatContactLinkSchema).max(6),
});

const ExperienceCardSchema = z.object({
  type: z.literal("ExperienceCard"),
  title: text(200),
  organization: text(200).nullable(),
  startedOn: IsoDateSchema,
  endedOn: IsoDateSchema.nullable(),
  summary: text(1000).nullable(),
  technologies: z.array(text(100)).max(20),
  href: SitePathSchema,
});

const ServiceCardSchema = z.object({
  type: z.literal("ServiceCard"),
  title: text(200),
  summary: text(1000),
  href: SitePathSchema,
});

const ExplorationCardSchema = z.object({
  type: z.literal("ExplorationCard"),
  title: text(200),
  summary: text(1000).nullable(),
  status: z.enum(explorationStatuses).meta({
    description: "The exploration's stored status; never shown stronger than stored.",
  }),
  href: SitePathSchema,
});

/**
 * An AI Roadmap area, module or resource. `href` is its page: `/ai-roadmap/<area>`,
 * `/ai-roadmap/<area>/<module>`, or a resource as `/ai-roadmap/<area>/<module>#resource-<slug>`.
 */
const RoadmapCardSchema = z.object({
  type: z.literal("RoadmapCard"),
  title: text(200),
  summary: text(1000).nullable(),
  href: SitePathSchema,
});

/** One complete typed block of an answer; rendered only once its whole payload validates. */
export const ChatBlockSchema = z
  .discriminatedUnion("type", [
    ContactCardSchema,
    ExperienceCardSchema,
    ServiceCardSchema,
    ExplorationCardSchema,
    RoadmapCardSchema,
  ])
  .meta({ id: "ChatBlock" });

export type ChatBlock = z.infer<typeof ChatBlockSchema>;

const eventBase = {
  requestId: z.uuid(),
  messageId: z.uuid(),
  eventId: z.int().nonnegative().meta({ description: "Grows with each event of the attempt." }),
};

/** One event of an answer attempt. */
export const ChatStreamEventSchema = z
  .discriminatedUnion("type", [
    z.object({ ...eventBase, type: z.literal("start") }),
    z.object({ ...eventBase, type: z.literal("text_delta"), text: z.string().min(1).max(4000) }),
    z.object({ ...eventBase, type: z.literal("block"), block: ChatBlockSchema }),
    z.object({ ...eventBase, type: z.literal("sources"), sources: ChatSourcesSchema }),
    z.object({
      ...eventBase,
      type: z.literal("related"),
      links: z.array(ChatRelatedLinkSchema).min(1).max(2),
    }),
    z.object({ ...eventBase, type: z.literal("complete"), outcome: z.enum(chatOutcomes) }),
    z.object({
      ...eventBase,
      type: z.literal("error"),
      code: z.enum(chatErrorCodes),
      retryable: z.boolean(),
    }),
  ])
  .meta({ id: "ChatStreamEvent" });

export type ChatStreamEvent = z.infer<typeof ChatStreamEventSchema>;

/** How an attempt ended. */
export type ChatTerminal =
  | { readonly type: "complete"; readonly outcome: ChatOutcome }
  | { readonly type: "error"; readonly code: ChatErrorCode; readonly retryable: boolean };

/** What is known of one answer attempt after the events accepted so far. */
export interface ChatAttempt {
  readonly requestId: string;
  /** Set by the first accepted event. */
  readonly messageId: string | null;
  /** -1 before the first event. */
  readonly lastEventId: number;
  readonly started: boolean;
  readonly sources: boolean;
  readonly related: boolean;
  readonly terminal: ChatTerminal | null;
}

/** Why an event cannot belong where it arrived. */
export type ChatOrderViolation =
  | "missing_start"
  | "repeated_start"
  | "foreign_request"
  | "foreign_message"
  | "after_terminal"
  | "repeated_sources"
  | "repeated_related";

export type ChatEventStep =
  | { readonly status: "accepted"; readonly attempt: ChatAttempt }
  | { readonly status: "duplicate" }
  | { readonly status: "invalid"; readonly reason: ChatOrderViolation };

/** An attempt for the request, before any event. */
export function startChatAttempt(requestId: string): ChatAttempt {
  return {
    requestId,
    messageId: null,
    lastEventId: -1,
    started: false,
    sources: false,
    related: false,
    terminal: null,
  };
}

/**
 * Applies one validated event to an attempt: accepted with the new attempt, a duplicate to ignore
 * (its identifier is not above the last accepted one) or invalid with the order rule it breaks.
 * Identifiers rise strictly within an attempt, so an event with a lower identifier that was never
 * seen is still a duplicate: it is ignored, not reported as an order violation, because a replayed
 * or reordered delivery must not fail an answer that already moved past it.
 * Pure; never throws.
 */
export function advanceChatAttempt(attempt: ChatAttempt, event: ChatStreamEvent): ChatEventStep {
  if (event.requestId !== attempt.requestId) return invalid("foreign_request");
  if (attempt.messageId !== null && event.messageId !== attempt.messageId) {
    return invalid("foreign_message");
  }
  if (event.eventId <= attempt.lastEventId) return { status: "duplicate" };
  if (attempt.terminal !== null) return invalid("after_terminal");

  const next = { ...attempt, messageId: event.messageId, lastEventId: event.eventId };
  switch (event.type) {
    case "start":
      return attempt.started ? invalid("repeated_start") : accepted({ ...next, started: true });
    case "error":
      return accepted({
        ...next,
        terminal: { type: "error", code: event.code, retryable: event.retryable },
      });
    default:
      break;
  }
  if (!attempt.started) return invalid("missing_start");
  switch (event.type) {
    case "sources":
      return attempt.sources ? invalid("repeated_sources") : accepted({ ...next, sources: true });
    case "related":
      return attempt.related ? invalid("repeated_related") : accepted({ ...next, related: true });
    case "complete":
      return accepted({ ...next, terminal: { type: "complete", outcome: event.outcome } });
    default:
      return accepted(next);
  }
}

function accepted(attempt: ChatAttempt): ChatEventStep {
  return { status: "accepted", attempt };
}

function invalid(reason: ChatOrderViolation): ChatEventStep {
  return { status: "invalid", reason };
}

export type ChatStreamValidation =
  | {
      readonly status: "complete";
      readonly events: ChatStreamEvent[];
      readonly terminal: ChatTerminal;
    }
  | { readonly status: "interrupted"; readonly events: ChatStreamEvent[] }
  | {
      readonly status: "invalid";
      readonly index: number;
      readonly reason: ChatOrderViolation | "malformed_event";
    };

/**
 * Checks a whole received stream for one request: every event parses, the order holds and one
 * terminal event ends it. Returns the accepted events without duplicates; a stream without its
 * terminal event is interrupted; the first malformed or misplaced event makes it invalid. The
 * contract scenarios every chat adapter — mock or real — must satisfy.
 */
export function validateChatStream(
  requestId: string,
  events: readonly unknown[],
): ChatStreamValidation {
  let attempt = startChatAttempt(requestId);
  const accepted: ChatStreamEvent[] = [];
  for (const [index, raw] of events.entries()) {
    const parsed = ChatStreamEventSchema.safeParse(raw);
    if (!parsed.success) return { status: "invalid", index, reason: "malformed_event" };
    const step = advanceChatAttempt(attempt, parsed.data);
    if (step.status === "invalid") return { status: "invalid", index, reason: step.reason };
    if (step.status === "accepted") {
      attempt = step.attempt;
      accepted.push(parsed.data);
    }
  }
  return attempt.terminal === null
    ? { status: "interrupted", events: accepted }
    : { status: "complete", events: accepted, terminal: attempt.terminal };
}
