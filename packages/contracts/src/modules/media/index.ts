import { z } from "zod";

/**
 * The accepted media types: PNG, JPEG and WebP images and PDF documents. The type of a stored
 * file is the one its content proves, never the one a caller declared.
 */
export const mediaTypes = ["image/png", "image/jpeg", "image/webp", "application/pdf"] as const;

export type MediaType = (typeof mediaTypes)[number];

const MediaIdSchema = z.uuid().meta({ description: "The identifier of the media." });

const AltTextSchema = z
  .string()
  .trim()
  .min(1)
  .max(1000)
  .nullable()
  .meta({ description: "Text that describes an image for people who cannot see it." });

const dimension = (description: string) =>
  z
    .int()
    .positive()
    .nullable()
    .meta({ description: `${description}; \`null\` for a PDF.` });

/** An uploaded file: its storage key, the type its content proves, its size and its alt text. */
export const MediaSchema = z
  .object({
    id: MediaIdSchema,
    key: z.string().min(1).meta({
      description: "The storage key, generated by the API. Never a deployment-specific address.",
    }),
    mediaType: z.enum(mediaTypes),
    byteSize: z.int().positive().meta({ description: "The size of the file in bytes." }),
    width: dimension("The image width in pixels"),
    height: dimension("The image height in pixels"),
    altText: AltTextSchema,
    url: z.url({ protocol: /^https?$/ }).meta({
      description: "The public address of the file, computed from the configured public base.",
    }),
    createdAt: z.iso.datetime(),
    updatedAt: z.iso.datetime(),
  })
  .meta({ id: "Media" });

/** Every media record, newest first. */
export const MediaListSchema = z
  .array(MediaSchema)
  .meta({ id: "MediaList", description: "Ordered by creation, newest first, then by identifier." });

/** Body of updating media: only the alt text can change; the file itself cannot be replaced. */
export const MediaUpdateSchema = z
  .strictObject({ altText: AltTextSchema })
  .partial()
  .refine((change) => Object.keys(change).length > 0, { message: "Change at least one field." })
  .meta({ id: "MediaUpdate" });

/**
 * The `multipart/form-data` body of an upload: one file and an optional alt text, nothing else. The
 * filename and the declared type of the part never choose where or as what the file is stored.
 */
export const MediaUploadSchema = z
  .strictObject({
    file: z.string().meta({
      format: "binary",
      description:
        "A PNG, JPEG or WebP image or a PDF. Its declared type and extension must match its content.",
    }),
    altText: z.string().trim().min(1).max(1000).optional().meta({
      description: "Text that describes an image for people who cannot see it.",
    }),
  })
  .meta({ id: "MediaUpload" });

/** The media identifier in a path. */
export const MediaIdParamsSchema = z.strictObject({ id: MediaIdSchema });

export type Media = z.infer<typeof MediaSchema>;
export type MediaUpdate = z.output<typeof MediaUpdateSchema>;
export type MediaUpload = z.output<typeof MediaUploadSchema>;
export type MediaIdParams = z.infer<typeof MediaIdParamsSchema>;
