from __future__ import annotations

from collections.abc import Mapping
from typing import Any, Self, TypeVar
from uuid import UUID

from attrs import define as _attrs_define

T = TypeVar("T", bound="ChatCompactionSubmission")


@_attrs_define
class ChatCompactionSubmission:
    """
    Attributes:
        request_id (UUID): This compaction's request, generated by the client; repeating it recovers the compaction.
        challenge_token (str): The bot-challenge token of this compaction; redeemed once, never stored.
    """

    request_id: UUID
    challenge_token: str

    def to_dict(self) -> dict[str, Any]:
        request_id = str(self.request_id)

        challenge_token = self.challenge_token

        field_dict: dict[str, Any] = {}

        field_dict.update(
            {
                "requestId": request_id,
                "challengeToken": challenge_token,
            }
        )

        return field_dict

    @classmethod
    def from_dict(cls, src_dict: Mapping[str, Any]) -> Self:
        d = dict(src_dict)
        request_id = UUID(d.pop("requestId"))

        challenge_token = d.pop("challengeToken")

        chat_compaction_submission = cls(
            request_id=request_id,
            challenge_token=challenge_token,
        )

        return chat_compaction_submission
