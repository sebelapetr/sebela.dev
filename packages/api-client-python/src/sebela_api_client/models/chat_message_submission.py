from __future__ import annotations

from collections.abc import Mapping
from typing import Any, Self, TypeVar
from uuid import UUID

from attrs import define as _attrs_define

T = TypeVar("T", bound="ChatMessageSubmission")


@_attrs_define
class ChatMessageSubmission:
    """
    Attributes:
        request_id (UUID): This question's request, generated by the client; a retry reuses it and recovers it.
        question (str):
        challenge_token (str): The bot-challenge token of this submission; redeemed once, never stored.
    """

    request_id: UUID
    question: str
    challenge_token: str

    def to_dict(self) -> dict[str, Any]:
        request_id = str(self.request_id)

        question = self.question

        challenge_token = self.challenge_token

        field_dict: dict[str, Any] = {}

        field_dict.update(
            {
                "requestId": request_id,
                "question": question,
                "challengeToken": challenge_token,
            }
        )

        return field_dict

    @classmethod
    def from_dict(cls, src_dict: Mapping[str, Any]) -> Self:
        d = dict(src_dict)
        request_id = UUID(d.pop("requestId"))

        question = d.pop("question")

        challenge_token = d.pop("challengeToken")

        chat_message_submission = cls(
            request_id=request_id,
            question=question,
            challenge_token=challenge_token,
        )

        return chat_message_submission
