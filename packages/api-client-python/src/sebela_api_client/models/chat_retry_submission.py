from __future__ import annotations

from collections.abc import Mapping
from typing import Any, Self, TypeVar
from uuid import UUID

from attrs import define as _attrs_define

T = TypeVar("T", bound="ChatRetrySubmission")


@_attrs_define
class ChatRetrySubmission:
    """
    Attributes:
        retry_id (UUID): This retry's own idempotency key, generated by the client; repeating it recovers the retry.
        challenge_token (str): The bot-challenge token of this retry; redeemed once, never stored.
    """

    retry_id: UUID
    challenge_token: str

    def to_dict(self) -> dict[str, Any]:
        retry_id = str(self.retry_id)

        challenge_token = self.challenge_token

        field_dict: dict[str, Any] = {}

        field_dict.update(
            {
                "retryId": retry_id,
                "challengeToken": challenge_token,
            }
        )

        return field_dict

    @classmethod
    def from_dict(cls, src_dict: Mapping[str, Any]) -> Self:
        d = dict(src_dict)
        retry_id = UUID(d.pop("retryId"))

        challenge_token = d.pop("challengeToken")

        chat_retry_submission = cls(
            retry_id=retry_id,
            challenge_token=challenge_token,
        )

        return chat_retry_submission
